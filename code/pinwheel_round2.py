"""
pinwheel_round2.py -- Topic 34 (B1), ROUND 2 experiments for the manuscript.

Purely additive on top of `pinwheel_sim.py` (round 1, kept byte-identical; a copy of the
round-1 file is pinwheel_sim.bak_20260905_round1.py).  Round-1 results E1/E2/E3 are
regenerated by `python pinwheel_sim.py --exp all`; this module adds:

  E1b  admission conservatism: fraction of *schedulable* profiles that the O(1) density test
       (Cor. 2) refuses, per density bin.  Derived from results/E1_density_sweep.json.
  E4   fleet dimensioning over the whole 121-camera corpus: number of edge boxes needed by
       (a) harmonic rounding + FFD into unit-density boxes (Cor. 3, provable factor 2),
       (b) FFD into 5/6-capacity boxes (heuristic -- no bound is claimed for it),
       (c) EDF-fit (open a new box when lazy EDF violates), sweeping K_target.
  E5   admission control under churn: cameras join/leave (Poisson), density admission
       (Cor. 2, thresholds 5/6 and 1 with harmonic rounding) vs admit-then-EDF.
  E6   escalation blackouts (Prop. 3): l in {2,4,8}, P_e in {50,100,200}.
  E7   energy and consolidation gain for every E2 configuration, in units of the idle slot
       energy E_idle.  The linear slot model e(a) = 1 + a (r - 1) has a single free
       parameter, r = E_active / E_idle; E7 is computed over the grid r in {3, 10, 30}.
       No absolute power figure is claimed: r is a platform parameter, not a measurement.
  E8   sensitivity: (i) shaping windows fitted on the first half of each camera's history and
       replayed on the second half (no oracle); (ii) per-dataset split CDnet2014/LASIESTA/BMC;
       (iii) a certified-latency cap K_max on the shaping grid.

Usage:  python pinwheel_round2.py --exp E1b|E4|E5|E6|E7|E8|figs|all [--quick]
Seed 42 throughout.  Outputs results/E4_*.json ... results/E8_*.json + figures.
"""
