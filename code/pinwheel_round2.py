def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--exp", default="all",
                    choices=["E1b", "E4", "E5", "E6", "E7", "E8", "figs", "all"])
    ap.add_argument("--quick", action="store_true")
    a = ap.parse_args()
    os.makedirs(RESULTS, exist_ok=True)
    random.seed(SEED)
    np.random.seed(SEED)
    videos, nframes, events, meta = load_corpus()
    print("corpus:", meta["n_videos"], "videos /", meta["n_events"], "events")
    t0 = time.time()
    if a.exp in ("E1b", "all"):
        o = run_E1b()
        print("E1b:", json.dumps(o["overall"]), f"[{time.time()-t0:.1f}s]")
    if a.exp in ("E4", "all"):
        o = run_E4(a.quick, videos, nframes, events)
        print("E4 rows:", len(o["rows"]), f"[{time.time()-t0:.1f}s]")
    if a.exp in ("E5", "all"):
        o = run_E5(a.quick, videos, nframes, events)
        print("E5 rows:", len(o["summary"]), f"[{time.time()-t0:.1f}s]")
    if a.exp in ("E6", "all"):
        o = run_E6(a.quick, videos, nframes, events)
        print("E6 prediction:", o["prediction_cells_correct"], "/", o["prediction_cells"],
              f"[{time.time()-t0:.1f}s]")
    if a.exp in ("E7", "all"):
        o = run_E7()
        print("E7 gain:", round(o["gain_min"], 3), "-", round(o["gain_max"], 3),
              f"[{time.time()-t0:.1f}s]")
    if a.exp in ("E8", "all"):
        o = run_E8(a.quick, videos, nframes, events)
        print("E8 holdout mean gain %:", round(o["holdout"]["mean_gain_holdout_pct"], 2),
              "oracle:", round(o["holdout"]["mean_gain_oracle_pct"], 2), f"[{time.time()-t0:.1f}s]")
    if a.exp in ("figs", "all"):
        make_figs2()
        print("figs written", f"[{time.time()-t0:.1f}s]")


if __name__ == "__main__":
    main()
