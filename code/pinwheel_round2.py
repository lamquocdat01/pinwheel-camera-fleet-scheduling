def eval_profile(streams, K, H, scheduler="harmonic"):
    if scheduler == "harmonic":
        sched, _ = harmonic_schedule(K, H)
        if sched is None:
            return None
    elif scheduler == "rr":
        sched = rr_schedule(K, H)
    else:
        sched = edf_schedule(K, H, lazy=True)
    warm = max(K)
    gaps = max_gaps(sched, len(K), H, warm)
    rp = replay(sched, streams, K, warm)
    return {"miss_all_rate": rp["miss_all"] / max(1, rp["n_events"]),
            "miss_cert": rp["miss_cert"], "n_cert": rp["n_cert"], "n_events": rp["n_events"],
            "violating_cameras": sum(1 for i, g in enumerate(gaps) if g > K[i]),
            "busy": float(np.mean(sched[warm:] >= 0)), "rho": density(K),
            "lat_max_cert": rp["lat_max_cert"]}


def run_E8(quick, videos, nframes, events):
    H = 3000 if quick else 6000
    seeds = 6 if quick else 12
    Ns = [6, 8, 12]
    budgets = [0.5, 2 / 3, 5 / 6, 1.0]
    out = {"meta": {"seed": SEED, "H": H, "seeds": seeds, "Ns": Ns, "budgets": budgets}}

    # ---- (i) HOLD-OUT: fit shaping windows on the first half, evaluate on the second -----
    # A temporal split needs at least one event in each half; only some videos qualify.
    eligible = [v for v in videos
                if any(e[0] < nframes[v] // 2 for e in events[v])
                and any(e[0] >= nframes[v] // 2 for e in events[v])]
    out["meta"]["holdout_eligible_videos"] = len(eligible)
    out["meta"]["holdout_total_videos"] = len(videos)
    rows = []
    for N in Ns:
        for rho_star in budgets:
            for sd in range(seeds):
                rng = random.Random(SEED * 1000 + sd)
                vs = rng.sample(eligible, N)
                tr = split_streams(vs, nframes, events, H, "train")
                te = split_streams(vs, nframes, events, H, "test")
                if min(len(s["raw_events"]) for s in tr) == 0 or \
                   min(len(s["raw_events"]) for s in te) == 0:
                    continue
                Ku = max(2, math.ceil(N / rho_star))
                K_uniform = [Ku] * N
                K_oracle = shaped_harmonic_windows(te, rho_star)[0]     # fitted on TEST (oracle)
                K_fit = shaped_harmonic_windows(tr, rho_star)[0]        # fitted on TRAIN
                r = {"N": N, "rho_star": rho_star, "seed": sd}
                for tag, K in (("uniform", K_uniform), ("shaped_oracle", K_oracle),
                               ("shaped_holdout", K_fit)):
                    e = eval_profile(te, K, H, "harmonic")
                    if e is None:
                        e = eval_profile(te, K, H, "edf")
                        e["constructive"] = False
                    else:
                        e["constructive"] = True
                    r[tag] = e
                    r[tag + "_K"] = K
                rows.append(r)
    agg = defaultdict(list)
    for r in rows:
        agg[(r["N"], round(r["rho_star"], 4))].append(r)
    hold = []
    for k, R in sorted(agg.items()):
        m = {tag: float(np.mean([r[tag]["miss_all_rate"] for r in R]))
             for tag in ("uniform", "shaped_oracle", "shaped_holdout")}
        hold.append({"N": k[0], "rho_star": k[1], "n": len(R), **{"miss_" + t: v for t, v in m.items()},
                     "gain_oracle_pct": 100.0 * (m["shaped_oracle"] - m["uniform"]) / m["uniform"],
                     "gain_holdout_pct": 100.0 * (m["shaped_holdout"] - m["uniform"]) / m["uniform"],
                     "miss_cert_total": int(sum(r["shaped_holdout"]["miss_cert"] for r in R)),
                     "n_cert_total": int(sum(r["shaped_holdout"]["n_cert"] for r in R))})
    out["holdout"] = {"rows": hold,
                      "note": "negative gain = shaping beats uniform; oracle fits K on the evaluation half, holdout fits on the other half",
                      "mean_gain_oracle_pct": float(np.mean([h["gain_oracle_pct"] for h in hold])),
                      "mean_gain_holdout_pct": float(np.mean([h["gain_holdout_pct"] for h in hold])),
                      "holdout_wins_cells": int(sum(1 for h in hold if h["gain_holdout_pct"] < 0)),
                      "cells": len(hold)}

    # ---- (ii) PER-DATASET -----------------------------------------------------------
    per = []
    for ds in ("CDnet2014", "LASIESTA", "BMC"):
        vs = [v for v in videos if v[0] == ds]
        for N in Ns:
            if len(vs) < N:
                continue
            for rho_star in budgets:
                acc = defaultdict(list)
                for sd in range(seeds):
                    rng = random.Random(SEED * 1000 + sd)
                    sub = rng.sample(vs, N)
                    streams = all_streams(sub, nframes, events, H)
                    Ku = max(2, math.ceil(N / rho_star))
                    for tag, K in (("uniform", [Ku] * N),
                                   ("shaped_harm", shaped_harmonic_windows(streams, rho_star)[0])):
                        e = eval_profile(streams, K, H, "harmonic")
                        if e is None:
                            continue
                        acc[tag].append(e)
                if not acc.get("uniform") or not acc.get("shaped_harm"):
                    continue
                mu = float(np.mean([e["miss_all_rate"] for e in acc["uniform"]]))
                ms = float(np.mean([e["miss_all_rate"] for e in acc["shaped_harm"]]))
                per.append({"dataset": ds, "n_videos": len(vs), "N": N, "rho_star": rho_star,
                            "miss_uniform": mu, "miss_shaped": ms,
                            "gain_pct": 100.0 * (ms - mu) / mu,
                            "miss_cert_total": int(sum(e["miss_cert"] for e in acc["shaped_harm"])),
                            "n_cert_total": int(sum(e["n_cert"] for e in acc["shaped_harm"]))})
    out["per_dataset"] = {"rows": per,
                          "duration_stats": {ds: {
                              "n_videos": sum(1 for v in videos if v[0] == ds),
                              "n_events": int(sum(len(events[v]) for v in videos if v[0] == ds)),
                              "median_duration": float(np.median(
                                  [d for v in videos if v[0] == ds for (_, d) in events[v]])),
                              "p90_duration": float(np.percentile(
                                  [d for v in videos if v[0] == ds for (_, d) in events[v]], 90)),
                              "mean_duration": float(np.mean(
                                  [d for v in videos if v[0] == ds for (_, d) in events[v]]))}
                              for ds in ("CDnet2014", "LASIESTA", "BMC")}}

    # ---- (iii) CERTIFIED-LATENCY CAP K_max ------------------------------------------
    cap_rows = []
    for N in Ns:
        for rho_star in budgets:
            for Kmax in (16, 32, 64):
                acc = []
                for sd in range(seeds):
                    rng = random.Random(SEED * 1000 + sd)
                    streams = build_streams(rng, videos, nframes, events, N, H)
                    best = None
                    for a in range(2, 17):
                        grid = [a << j for j in range(0, 8) if (a << j) <= Kmax]
                        if len(grid) < 2:
                            continue
                        K = shaped_windows(streams, rho_star, grid=grid)
                        o = shaping_objective(streams, K)
                        if best is None or o < best[0]:
                            best = (o, K)
                    if best is None:
                        continue
                    e = eval_profile(streams, best[1], H, "harmonic")
                    if e is None:
                        continue
                    acc.append(e)
                if acc:
                    cap_rows.append({"N": N, "rho_star": rho_star, "K_max": Kmax, "n": len(acc),
                                     "miss_all_rate": float(np.mean([e["miss_all_rate"] for e in acc])),
                                     "lat_max_cert": int(max(e["lat_max_cert"] for e in acc)),
                                     "miss_cert_total": int(sum(e["miss_cert"] for e in acc)),
                                     "n_cert_total": int(sum(e["n_cert"] for e in acc))})
    out["latency_cap"] = {"rows": cap_rows,
                          "note": "K_max caps the certified latency (Lemma 1 gives L <= K_i - 1) at the cost of a coarser shaping grid"}

    # ---- (iv) ROUND-ROBIN baseline (R2-6) -------------------------------------------
    rr_rows = []
    for N in Ns:
        for rho_star in budgets:
            acc_rr, acc_h = [], []
            for sd in range(seeds):
                rng = random.Random(SEED * 1000 + sd)
                streams = build_streams(rng, videos, nframes, events, N, H)
                Ku = max(2, math.ceil(N / rho_star))
                K = [Ku] * N
                acc_rr.append(eval_profile(streams, K, H, "rr"))
                e = eval_profile(streams, K, H, "harmonic")
                if e:
                    acc_h.append(e)
            rr_rows.append({"N": N, "rho_star": rho_star,
                            "rr_miss": float(np.mean([e["miss_all_rate"] for e in acc_rr])),
                            "rr_busy": float(np.mean([e["busy"] for e in acc_rr])),
                            "rr_violating": int(sum(e["violating_cameras"] for e in acc_rr)),
                            "harm_miss": float(np.mean([e["miss_all_rate"] for e in acc_h])) if acc_h else None,
                            "harm_busy": float(np.mean([e["busy"] for e in acc_h])) if acc_h else None,
                            "harm_violating": int(sum(e["violating_cameras"] for e in acc_h)) if acc_h else None})
    out["round_robin_baseline"] = {"rows": rr_rows,
                                   "note": "work-conserving proportional-share round robin: busy = 1 always, so it spends the full energy budget"}
    json.dump(out, open(os.path.join(RESULTS, "E8_sensitivity.json"), "w"), indent=1)
    return out


